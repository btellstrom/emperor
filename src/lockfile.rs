//! The lockfile records the fingerprint of every justification at the time a
//! human accepted it. Only emperor writes this file.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use crate::Result;

pub const LOCKFILE_NAME: &str = "emperor.lock";

/// Item UID -> justification key -> fingerprint.
pub type Fingerprints = BTreeMap<String, BTreeMap<String, String>>;

pub fn read(root: &Path) -> Result<Fingerprints> {
    let path = root.join(LOCKFILE_NAME);
    if !path.exists() {
        return Ok(Fingerprints::new());
    }
    toml::from_str(&fs::read_to_string(&path)?).map_err(|e| format!("{}: {e}", path.display()).into())
}

pub fn write(root: &Path, fingerprints: &Fingerprints) -> Result<()> {
    let body = toml::to_string(fingerprints)?;
    let header = "# Generated by `emperor accept`. Do not edit by hand.\n\n";
    fs::write(root.join(LOCKFILE_NAME), format!("{header}{body}"))?;
    Ok(())
}
